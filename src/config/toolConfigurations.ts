export type WorkspaceType = 
  | 'document-grid'  // Grid of uploaded file cards (Merge, Compress, JPG to PDF, etc.)
  | 'page-grid'      // Grid of individual page thumbnails (Split, Organize, Remove, Extract, Rotate)
  | 'single-preview' // Full page document view with interactive overlay (Crop, Watermark, Sign, Edit, Redact, Form)
  | 'dual-preview';  // Side-by-side document compare (Compare PDF)

export type OutputFileType = 'pdf' | 'docx' | 'xlsx' | 'pptx' | 'jpg' | 'png' | 'zip' | 'txt' | 'md' | 'json';

