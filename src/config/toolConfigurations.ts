export const getToolConfig = (idOrSlug: string): ToolConfigSchema => {
  if (TOOL_CONFIGURATIONS[idOrSlug]) return TOOL_CONFIGURATIONS[idOrSlug];
  const found = Object.values(TOOL_CONFIGURATIONS).find(
    c => c.slug === idOrSlug || c.id === idOrSlug || c.slug === `/${idOrSlug}`
  );
  if (found) return found;

  // Fallback schema
  const cleanId = idOrSlug.replace(/^\//, '');
  const title = cleanId.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  return {
    id: cleanId,
    title,
    slug: `/${cleanId}`,
    acceptedFileTypes: ['application/pdf', '.pdf'],
    multiple: true,
    minFiles: 1,
    workspaceType: 'document-grid',
    primaryButtonText: `${title} →`,
    processingMessage: `Processing ${title}...`,
    outputType: 'pdf',
    description: `Process your PDF with ${title}.`,
  };
};
